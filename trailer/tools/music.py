"""Original instrumental score and sound effects for the Spine launch trailer, synthesised from scratch.

No samples, no third-party recordings: every sound is generated by the code below, so the audio's
provenance is this file. Deterministic (no randomness except a fixed-seed noise generator).

Writes public/assets/audio/music.wav, sfx.wav and mix.wav (48 kHz stereo, 80 s).
Usage: python3 -I tools/music.py
"""
import os
import wave
import numpy as np

SR = 48000
DUR = 80.0
N = int(SR * DUR)
BPM = 110
BEAT = 60 / BPM
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "public", "assets", "audio")
rng = np.random.default_rng(7)

# Section cues in seconds (scene timing from src/timeline.js)
WELCOME = 6.0         # logo lands
JOIN = 36.9           # Jamie joins, fuller texture
BLOCK = 51.3          # blocker: brief reduction
RECOVER = 57.3        # recovery check in
LIVE = 62.05          # Live
VERIFY = 69.45        # Verified: resolution
END_CHORD = 75.3      # closing chord with the logo

def t_axis(n):
    return np.arange(n) / SR

def note_hz(m):
    return 440.0 * 2 ** ((m - 69) / 12)

def env_adsr(n, a, d, s, r, sus_len=None):
    a, d, r = int(a * SR), int(d * SR), int(r * SR)
    sus = n - a - d - r if sus_len is None else int(sus_len * SR)
    sus = max(sus, 0)
    e = np.concatenate([np.linspace(0, 1, max(a, 1)), np.linspace(1, s, max(d, 1)), np.full(sus, s), np.linspace(s, 0, max(r, 1))])
    return e[:n] if len(e) >= n else np.pad(e, (0, n - len(e)))

def add(buf, start, sig, gain=1.0, pan=0.0):
    i = int(start * SR)
    if i >= N:
        return
    sig = sig[: N - i]
    l, r = np.cos((pan + 1) * np.pi / 4), np.sin((pan + 1) * np.pi / 4)
    buf[0, i:i + len(sig)] += sig * gain * l * 1.414
    buf[1, i:i + len(sig)] += sig * gain * r * 1.414

def lowpass(x, cutoff):
    a = np.exp(-2 * np.pi * cutoff / SR)
    y = np.empty_like(x)
    acc = 0.0
    # one-pole low-pass; only used on short noise bursts
    for i, v in enumerate(x):
        acc = (1 - a) * v + a * acc
        y[i] = acc
    return y

# --- instruments -----------------------------------------------------------------------------------

def pad(midis, length, bright=0.5):
    n = int(length * SR)
    t = t_axis(n)
    s = np.zeros(n)
    for m in midis:
        f = note_hz(m)
        for det in (-0.12, 0.0, 0.11):
            ff = f * 2 ** (det / 12)
            s += np.sin(2 * np.pi * ff * t) + bright * 0.32 * np.sin(4 * np.pi * ff * t) + bright * 0.12 * np.sin(6 * np.pi * ff * t)
    s /= len(midis) * 3
    return s * env_adsr(n, 0.6, 0.4, 0.85, 1.2)

def pluck(m, length=0.9, bright=0.6):
    # Karplus-Strong plucked string
    f = note_hz(m)
    p = int(SR / f)
    n = int(length * SR)
    buf = rng.uniform(-1, 1, p) * bright + (1 - bright) * np.sin(2 * np.pi * np.arange(p) / p)
    out = np.zeros(n)
    for i in range(n):
        v = buf[i % p]
        out[i] = v
        buf[i % p] = 0.996 * 0.5 * (v + buf[(i + 1) % p])
    return out * env_adsr(n, 0.002, 0.05, 0.9, 0.2)

_pluck_cache = {}
def pluck_c(m, length=0.9, bright=0.6):
    k = (m, length, bright)
    if k not in _pluck_cache:
        _pluck_cache[k] = pluck(m, length, bright)
    return _pluck_cache[k]

def bass(m, length):
    n = int(length * SR)
    t = t_axis(n)
    f = note_hz(m)
    s = np.sin(2 * np.pi * f * t) + 0.25 * np.sin(4 * np.pi * f * t)
    s = np.tanh(1.4 * s) / np.tanh(1.4)
    return s * env_adsr(n, 0.01, 0.15, 0.7, 0.12)

def kick():
    n = int(0.35 * SR)
    t = t_axis(n)
    f = 45 + 75 * np.exp(-t * 28)
    ph = 2 * np.pi * np.cumsum(f) / SR
    return np.sin(ph) * np.exp(-t * 9) * 0.9

def shaker():
    n = int(0.07 * SR)
    x = rng.uniform(-1, 1, n)
    x = x - lowpass(x, 5000)
    return x * np.exp(-t_axis(n) * 60) * 0.5

def clap():
    n = int(0.22 * SR)
    x = rng.uniform(-1, 1, n)
    x = lowpass(x, 3500) - lowpass(x, 900)
    e = np.zeros(n)
    for off in (0, 0.011, 0.022):
        i = int(off * SR)
        e[i:] += np.exp(-t_axis(n - i) * 38)
    return x * e * 1.6

def bell(m, length=2.4):
    n = int(length * SR)
    t = t_axis(n)
    f = note_hz(m)
    mod = np.sin(2 * np.pi * f * 3.5 * t) * 2.2 * np.exp(-t * 3)
    return np.sin(2 * np.pi * f * t + mod) * np.exp(-t * 2.2)

# --- score -----------------------------------------------------------------------------------------

# D major: Dmaj9, Bm7, Gmaj7, A(add4)
CHORDS = [
    (50, [62, 66, 69, 73, 76]),
    (47, [62, 66, 69, 71, 74]),
    (43, [62, 67, 71, 74, 78]),
    (45, [61, 64, 69, 71, 76]),
]
BAR = 4 * BEAT
music = np.zeros((2, N))

def chord_at(bar):
    return CHORDS[bar % 4]

def in_range(t, a, b):
    return a <= t < b

n_bars = int(DUR / BAR) + 1
for bar in range(n_bars):
    t0 = bar * BAR
    root, notes = chord_at(bar)
    if t0 >= 79.0:
        break
    # pad throughout, gently filtered down during the blocker
    reduce = in_range(t0, BLOCK - 0.6, RECOVER - 0.3)
    add(music, t0, pad(notes[:4], BAR + 1.2, bright=0.25 if reduce else 0.55), gain=0.16 if t0 < WELCOME - 0.2 else 0.19, pan=0)
    # playful plucks: 8th-note arpeggio, sparse at the start
    pattern = [0, 2, 1, 3, 4, 2, 3, 1]
    for k, idx in enumerate(pattern):
        tt = t0 + k * BEAT / 2
        if tt >= END_CHORD - 0.2:
            break
        if tt < WELCOME and k % 2:
            continue
        if reduce and k % 4:
            continue
        add(music, tt, pluck_c(notes[idx] + 12 * (k % 3 == 2), 0.8, 0.55), gain=0.11 if tt < WELCOME else 0.13, pan=-0.35 if k % 2 else 0.35)
    # second, higher pluck layer once the team forms
    if t0 >= JOIN - 0.3 and not reduce and t0 < END_CHORD - 0.2:
        for k in (1, 3, 6):
            add(music, t0 + k * BEAT / 2, pluck_c(notes[(k + 2) % 5] + 24, 0.6, 0.45), gain=0.06, pan=0.6 if k == 3 else -0.6)
    # bass from the idea chapter
    if t0 >= 28.0 - 0.3 and not reduce and t0 < END_CHORD - 0.2:
        for k in (0, 2, 3):
            add(music, t0 + k * BEAT, bass(root, BEAT * (0.9 if k else 1.8)), gain=0.17)
    # drums: light from the welcome, fuller from the join, out for the blocker
    if WELCOME - 0.1 <= t0 < END_CHORD - 0.2 and not reduce:
        for b in range(4):
            tb = t0 + b * BEAT
            if b in (0, 2):
                add(music, tb, kick(), gain=0.30 if t0 >= JOIN - 0.3 else 0.22)
            if t0 >= JOIN - 0.3 and b in (1, 3):
                add(music, tb, clap(), gain=0.12, pan=0.1)
            for h in range(2):
                add(music, tb + h * BEAT / 2, shaker(), gain=0.10 if h else 0.06, pan=0.4)

# warm chord lift as the logo lands
add(music, WELCOME - 0.05, pad([62, 66, 69, 73, 78], 3.6, bright=0.8), gain=0.20)
add(music, WELCOME, bell(81, 3.0), gain=0.07, pan=0.2)
add(music, WELCOME, bell(74, 3.0), gain=0.06, pan=-0.2)
# resolution on verification
add(music, VERIFY, pad([62, 66, 69, 74, 78], 4.0, bright=0.8), gain=0.20)
add(music, VERIFY, bell(78, 3.0), gain=0.06, pan=0.2)
# closing cadence: A(sus) to D, ringing out naturally before the last frame
add(music, END_CHORD, pad([61, 64, 69, 71], 1.9, bright=0.6), gain=0.20)
add(music, END_CHORD + 1.75, pad([62, 66, 69, 74, 78], 3.0, bright=0.7), gain=0.24)
for i, m in enumerate([74, 78, 81, 86]):
    add(music, END_CHORD + 1.75 + i * 0.09, pluck_c(m, 2.2, 0.5), gain=0.10, pan=-0.3 + 0.2 * i)
add(music, END_CHORD + 1.75, bass(38, 2.4), gain=0.18)

# --- sound effects on the real actions (times from the source frame mappings in the scenes) ----------
sfx = np.zeros((2, N))

def click():
    n = int(0.05 * SR)
    t = t_axis(n)
    return (np.sin(2 * np.pi * 2200 * t) * 0.5 + rng.uniform(-1, 1, n) * 0.3) * np.exp(-t * 140)

def arrival():
    s = np.zeros(int(0.9 * SR))
    for i, m in enumerate((74, 78, 81)):
        b = bell(m, 0.8)
        j = int(i * 0.07 * SR)
        s[j:j + len(b)] += b[: len(s) - j] * 0.5
    return s

def live_chime():
    s = np.zeros(int(1.6 * SR))
    for i, m in enumerate((81, 86)):
        b = bell(m, 1.4)
        j = int(i * 0.11 * SR)
        s[j:j + len(b)] += b[: len(s) - j] * 0.55
    return s

CLICKS = [15.43, 32.87, 36.80, 45.37, 51.37, 55.10, 57.20, 62.00, 69.30]
for c in CLICKS:
    add(sfx, c, click(), gain=0.22)
add(sfx, 36.93, arrival(), gain=0.16)    # Jamie's arrival: 2 of 3
add(sfx, 62.07, live_chime(), gain=0.16)  # Live

# --- reverb, master ----------------------------------------------------------------------------------

def reverb(x, seconds=2.2, wet=0.22):
    n = int(seconds * SR)
    ir = np.stack([rng.standard_normal(n), rng.standard_normal(n)]) * np.exp(-t_axis(n) * 3.2)
    ir[:, : int(0.012 * SR)] = 0
    ir /= np.sqrt((ir ** 2).sum(axis=1, keepdims=True))
    size = 1 << int(np.ceil(np.log2(x.shape[1] + n)))
    out = np.fft.irfft(np.fft.rfft(x, size) * np.fft.rfft(ir, size), size)[:, : x.shape[1]]
    return x * (1 - wet) + out * wet

music = reverb(music, 2.4, 0.25)
sfx = reverb(sfx, 1.2, 0.15)
mix = music + sfx
# gentle end: the final chord rings out inside the 80 s (no fade to black needed)
tail = t_axis(int(0.6 * SR))
mix[:, -len(tail):] *= np.linspace(1, 0.0, len(tail)) ** 2

def write(name, x):
    x = x / max(1e-9, np.abs(x).max()) * 0.89
    pcm = (np.clip(x, -1, 1).T * 32767).astype("<i2")
    with wave.open(os.path.join(OUT, name), "wb") as w:
        w.setnchannels(2)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes(pcm.tobytes())

os.makedirs(OUT, exist_ok=True)
write("music.wav", music)
write("sfx.wav", sfx)
write("mix.wav", mix)
print("wrote music.wav, sfx.wav, mix.wav")


# --- short cues for the 15 s cut and the 18 s teaser (their own music, never the master sped up) -----

def short_cue(dur, resolve_at, name, drums_from=0.0, gentle=False):
    n = int(SR * dur)
    buf = np.zeros((2, n))

    def put(start, sig, gain=1.0, pan=0.0):
        i = int(start * SR)
        if i >= n:
            return
        sig = sig[: n - i]
        l, r = np.cos((pan + 1) * np.pi / 4), np.sin((pan + 1) * np.pi / 4)
        buf[0, i:i + len(sig)] += sig * gain * l * 1.414
        buf[1, i:i + len(sig)] += sig * gain * r * 1.414

    for bar in range(int(dur / BAR) + 1):
        t0 = bar * BAR
        if t0 >= resolve_at - 0.1:
            break
        root, notes = CHORDS[bar % 4]
        put(t0, pad(notes[:4], BAR + 1.2, bright=0.4 if gentle else 0.55), gain=0.19)
        for k, idx in enumerate([0, 2, 1, 3, 4, 2, 3, 1]):
            tt = t0 + k * BEAT / 2
            if tt < resolve_at - 0.1:
                put(tt, pluck_c(notes[idx] + 12 * (k % 3 == 2), 0.8, 0.55), gain=0.12, pan=-0.35 if k % 2 else 0.35)
        if not gentle and t0 >= drums_from - 0.05:
            for k in (0, 2, 3):
                put(t0 + k * BEAT, bass(root, BEAT * (0.9 if k else 1.8)), gain=0.16)
            for b in range(4):
                if b in (0, 2):
                    put(t0 + b * BEAT, kick(), gain=0.26)
                for h in range(2):
                    put(t0 + b * BEAT + h * BEAT / 2, shaker(), gain=0.09 if h else 0.05, pan=0.4)
    put(0.0, bell(81, 2.5), gain=0.06, pan=0.2)
    put(resolve_at, pad([62, 66, 69, 74, 78], dur - resolve_at + 0.5, bright=0.7), gain=0.24)
    put(resolve_at, bass(38, dur - resolve_at), gain=0.16)
    for i, m in enumerate([74, 78, 81, 86]):
        put(resolve_at + i * 0.09, pluck_c(m, 2.2, 0.5), gain=0.10, pan=-0.3 + 0.2 * i)
    out = reverb(buf, 2.2, 0.25)
    tail = t_axis(int(0.5 * SR))
    out[:, -len(tail):] *= np.linspace(1, 0.0, len(tail)) ** 2
    write(name, out)
    print("wrote", name)


short_cue(15.0, 12.2, "cut15.wav", drums_from=2.0)
short_cue(18.0, 15.9, "teaser.wav", gentle=True)
